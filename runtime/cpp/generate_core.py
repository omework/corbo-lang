"""Generate explicit primitive support functions; no templates or ownership machinery."""
from pathlib import Path

TYPES = [('i32', 'int32_t', 32, True), ('i64', 'int64_t', 64, True),
         ('u8', 'uint8_t', 8, False), ('u16', 'uint16_t', 16, False),
         ('u32', 'uint32_t', 32, False), ('u64', 'uint64_t', 64, False)]


def generate():
    out = ['''// SPDX-License-Identifier: MIT OR Apache-2.0
#ifndef CORBO_CPP_CORE_HPP
#define CORBO_CPP_CORE_HPP
#if defined(__linux__) && !defined(_GNU_SOURCE)
#define _GNU_SOURCE 1
#endif
#if defined(__APPLE__) && !defined(_DARWIN_C_SOURCE)
#define _DARWIN_C_SOURCE 1
#endif
// Generated by runtime/cpp/generate_core.py. All helpers are ordinary functions.
// Corbo controls evaluation order, storage and cleanup; C++ supplies no ownership.
#include <new> // Nonallocating placement initialization of plain datastack objects.
#include <stdint.h>
#include <stddef.h>
#include <stdio.h>
#include <stdlib.h>
#include <string.h>
#include <math.h>
#include <limits.h>
#include <float.h>

struct corbo_unit { uint8_t unused; };
struct corbo_text { uint8_t *data; size_t len; };

[[noreturn]] static inline void corbo_fail(const char *message) {
    fputs(message, stderr);
    fputc('\\n', stderr);
    exit(EXIT_FAILURE);
}

// Endpoints are checked in their original signedness before narrowing to size_t.
static inline size_t corbo_index_signed(int64_t value, size_t length) {
    if (value < 0 || (uint64_t)value >= length) corbo_fail("corbo: index out of bounds");
    return (size_t)value;
}
static inline size_t corbo_index_unsigned(uint64_t value, size_t length) {
    if (value >= length) corbo_fail("corbo: index out of bounds");
    return (size_t)value;
}
static inline size_t corbo_bound_signed(int64_t value, size_t length) {
    if (value < 0 || (uint64_t)value > length) corbo_fail("corbo: slice bound out of range");
    return (size_t)value;
}
static inline size_t corbo_bound_unsigned(uint64_t value, size_t length) {
    if (value > length) corbo_fail("corbo: slice bound out of range");
    return (size_t)value;
}
''']
    for name, ty, width, signed in TYPES:
        for op in ('add', 'sub', 'mul'):
            out.append(f'''static inline {ty} corbo_{name}_{op}({ty} a, {ty} b) {{
    {ty} result;
    if (__builtin_{op}_overflow(a, b, &result)) corbo_fail("corbo: integer {op} overflow");
    return result;
}}
''')
        lower = 'INT32_MIN' if width == 32 else 'INT64_MIN'
        for op, symbol in [('div', '/'), ('rem', '%')]:
            out.append(f'''static inline {ty} corbo_{name}_{op}({ty} a, {ty} b) {{
    if (b == 0) corbo_fail("corbo: division or remainder by zero");
''')
            if signed:
                tail = 'corbo_fail("corbo: integer division overflow");' if op == 'div' else 'return 0;'
                out.append(f'    if (a == {lower} && b == -1) {tail}\n')
            out.append(f'    return ({ty})(a {symbol} b);\n}}\n')
        out.append(f'''static inline {ty} corbo_{name}_shl({ty} value, uint64_t count) {{
    if (count >= {width}) corbo_fail("corbo: shift count exceeds integer width");
    // memcpy preserves the signed bit pattern without out-of-range conversion.
    uint{width}_t bits = (uint{width}_t)value;
    bits = (uint{width}_t)((uint64_t)bits << count);
    {ty} result;
    memcpy(&result, &bits, sizeof result);
    return result;
}}
static inline {ty} corbo_{name}_shr({ty} value, uint64_t count) {{
    if (count >= {width}) corbo_fail("corbo: shift count exceeds integer width");
    // C++20 specifies arithmetic right shift for signed integers.
    return ({ty})(value >> count);
}}
''')
    for name, ty in [('f32', 'float'), ('f64', 'double')]:
        for op, symbol in [('add', '+'), ('sub', '-'), ('mul', '*'), ('div', '/')]:
            out.append(f'static inline {ty} corbo_{name}_{op}({ty} a, {ty} b) {{\n')
            if op == 'div':
                out.append('    if (b == 0) corbo_fail("corbo: division by zero");\n')
            out.append(f'    return a {symbol} b;\n}}\n')
        fn = 'fmodf' if ty == 'float' else 'fmod'
        out.append(f'''static inline {ty} corbo_{name}_rem({ty} a, {ty} b) {{
    if (b == 0) corbo_fail("corbo: remainder by zero");
    return {fn}(a, b);
}}
''')
    numeric = TYPES + [('f32', 'float', 32, True), ('f64', 'double', 64, True)]
    for source, source_ty, source_width, source_signed in numeric:
        source_float = source[0] == 'f'
        for target, target_ty, target_width, target_signed in numeric:
            target_float = target[0] == 'f'
            out.append(f'static inline {target_ty} corbo_cast_{source}_{target}({source_ty} value) {{\n')
            if not source_float and not target_float:
                if source_signed and not target_signed:
                    out.append('    if (value < 0) corbo_fail("corbo: conversion out of range");\n')
                source_bits = source_width - int(source_signed)
                target_bits = target_width - int(target_signed)
                if target_bits < source_bits:
                    bound = ('INT' if target_signed else 'UINT') + str(target_width) + '_MAX'
                    out.append(f'    if ((uint64_t)value > (uint64_t){bound}) corbo_fail("corbo: conversion out of range");\n')
                    # A signed negative value is not compared as unsigned.
                    if source_signed and target_signed:
                        out[-1] = f'    if (value > {bound} || value < INT{target_width}_MIN) corbo_fail("corbo: conversion out of range");\n'
            elif source_float and not target_float:
                digits = target_width - int(target_signed)
                lower = f'-0x1p{digits}L' if target_signed else '0.0L'
                out.append(f'    long double wide = (long double)value;\n'
                           f'    if (!isfinite(wide) || wide < {lower} || wide >= 0x1p{digits}L || truncl(wide) != wide)\n'
                           '        corbo_fail("corbo: inexact numeric conversion");\n')
            elif not source_float and target_float:
                digits = source_width - int(source_signed)
                lower = f'-0x1p{digits}L' if source_signed else '0.0L'
                out.append(f'    {target_ty} converted = ({target_ty})value;\n'
                           f'    long double wide = (long double)converted;\n'
                           f'    if (!isfinite(wide) || wide < {lower} || wide >= 0x1p{digits}L || ({source_ty})converted != value)\n'
                           '        corbo_fail("corbo: inexact numeric conversion");\n'
                           '    return converted;\n}\n')
                continue
            else:
                if source_width > target_width:
                    out.append('    if (isfinite(value) && (value > FLT_MAX || value < -FLT_MAX))\n'
                               '        corbo_fail("corbo: floating conversion overflow");\n')
                out.append(f'    {target_ty} converted = ({target_ty})value;\n'
                           f'    if (isfinite(value) && ({source_ty})converted != value)\n'
                           '        corbo_fail("corbo: inexact numeric conversion");\n'
                           '    return converted;\n}\n')
                continue
            out.append(f'    return ({target_ty})value;\n}}\n')
    out.append('#endif\n')
    return ''.join(out)


if __name__ == '__main__':
    Path(__file__).with_name('core.hpp').write_text(generate())
