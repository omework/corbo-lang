//! Exhaustive syntax-to-semantic dispatch inventory. This classifies context;
//! it does not infer types, resolve names or prove language rules.
use crate::ast::NodeKind;

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum SemanticContext {
    Declaration,
    Annotation,
    Type,
    Pattern,
    Expression,
    Statement,
    Operand,
}

/// Adding syntax requires an explicit semantic producer/context decision here.
/// Context-only children are consumed by their owning semantic construct.
pub fn context(kind: &NodeKind) -> SemanticContext {
    match kind {
        NodeKind::Module { .. } => SemanticContext::Declaration,
        NodeKind::Import { .. } => SemanticContext::Declaration,
        NodeKind::ImportEntry { .. } => SemanticContext::Declaration,
        NodeKind::Function { .. } => SemanticContext::Declaration,
        NodeKind::Parameter { .. } => SemanticContext::Declaration,
        NodeKind::Struct { .. } => SemanticContext::Declaration,
        NodeKind::Enum { .. } => SemanticContext::Declaration,
        NodeKind::Field { .. } => SemanticContext::Declaration,
        NodeKind::Variant { .. } => SemanticContext::Declaration,
        NodeKind::Constant { .. } => SemanticContext::Declaration,
        NodeKind::Annotation { .. } => SemanticContext::Annotation,
        NodeKind::TypeContractAlternative { .. } => SemanticContext::Annotation,
        NodeKind::Property { .. } => SemanticContext::Annotation,
        NodeKind::Size { .. } => SemanticContext::Annotation,
        NodeKind::Conditional { .. } => SemanticContext::Annotation,
        NodeKind::Type(_) => SemanticContext::Type,
        NodeKind::Pattern(_) => SemanticContext::Pattern,
        NodeKind::Block { .. } => SemanticContext::Expression,
        NodeKind::Let { .. } => SemanticContext::Statement,
        NodeKind::Assignment { .. } => SemanticContext::Statement,
        NodeKind::ExpressionStatement { .. } => SemanticContext::Statement,
        NodeKind::Return { .. } => SemanticContext::Statement,
        NodeKind::Break { .. } => SemanticContext::Statement,
        NodeKind::Continue { .. } => SemanticContext::Statement,
        NodeKind::Yield { .. } => SemanticContext::Statement,
        NodeKind::NamedMove { .. } => SemanticContext::Statement,
        NodeKind::While { .. } => SemanticContext::Statement,
        NodeKind::For { .. } => SemanticContext::Statement,
        NodeKind::Path { .. } => SemanticContext::Expression,
        NodeKind::Literal { .. } => SemanticContext::Expression,
        NodeKind::Parenthesized { .. } => SemanticContext::Expression,
        NodeKind::Tuple { .. } => SemanticContext::Expression,
        NodeKind::Array { .. } => SemanticContext::Expression,
        NodeKind::Unary { .. } => SemanticContext::Expression,
        NodeKind::Binary { .. } => SemanticContext::Expression,
        NodeKind::Conversion { .. } => SemanticContext::Expression,
        NodeKind::Call { .. } => SemanticContext::Expression,
        NodeKind::Projection { .. } => SemanticContext::Expression,
        NodeKind::Index { .. } => SemanticContext::Expression,
        NodeKind::Range { .. } => SemanticContext::Operand,
        NodeKind::Await { .. } => SemanticContext::Expression,
        NodeKind::Propagate { .. } => SemanticContext::Expression,
        NodeKind::Unwrap { .. } => SemanticContext::Expression,
        NodeKind::Construct { .. } => SemanticContext::Expression,
        NodeKind::FieldInitializer { .. } => SemanticContext::Operand,
        NodeKind::Closure { .. } => SemanticContext::Expression,
        NodeKind::Async { .. } => SemanticContext::Expression,
        NodeKind::MoveBlock { .. } => SemanticContext::Expression,
        NodeKind::If { .. } => SemanticContext::Expression,
        NodeKind::LetCondition { .. } => SemanticContext::Operand,
        NodeKind::Match { .. } => SemanticContext::Expression,
        NodeKind::MatchArm { .. } => SemanticContext::Operand,
        NodeKind::Loop { .. } => SemanticContext::Expression,
        NodeKind::Unchecked { .. } => SemanticContext::Expression,
        NodeKind::Foreign { .. } => SemanticContext::Expression,
    }
}

